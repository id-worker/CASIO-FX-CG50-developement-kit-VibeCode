for code in range(32, 127):
    rows = RAW_FONT[code]
    assert len(rows) == 10, f"bad row count for {code}"
    vals = []
    for r in rows:
        assert len(r) == 6, f"bad width for {code}: {r}"
        b = 0
        for i, ch in enumerate(r):
            if ch == '#':
                b |= (1 << (5 - i))
        vals.append(f"0x{b:02X}")
    ch_comment = chr(code) if code != 92 else "backslash"
    lines.append(f"    {{ {', '.join(vals)} }}, /* {code}: {ch_comment} */")
lines.append("};")
lines.append("")
lines.append("#endif")

