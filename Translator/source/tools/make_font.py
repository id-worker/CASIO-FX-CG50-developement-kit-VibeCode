#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""make_font.py -- renders the embedded UI font (font_tr.h) for the Translator
add-in from DejaVuSansMono.ttf.

Cell: 9 x 14 px. Glyphs stored as 14 x uint16 (bit 15 = leftmost column).
Charset: ASCII 0x20-0x7E, « » …  , Cyrillic U+0401/U+0410-U+044F/U+0451.
"""
import os
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = os.environ.get("TRANSLATOR_FONT", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")
OUT = str(ROOT / "src" / "font_tr.h")

CELL_W, CELL_H = 9, 14
BASELINE = 11           # px from top of cell
FONT_SIZE = 12

def charset():
    chars = [chr(c) for c in range(0x20, 0x7F)]
    chars += ["«", "»", "…"]
    chars += [chr(c) for c in list(range(0x410, 0x450)) + [0x401, 0x451]]
    # extras found in dictionary data, if any:
    return chars

def scan_coverage(charset_set):
    extra = {}
    for path in (ROOT / "dicts/en_ru.tsv", ROOT / "dicts/ru_en.tsv"):
        with open(path, encoding="utf-8") as f:
            for line in f:
                for ch in line.rstrip("\n"):
                    if ch == "\t":
                        continue
                    if ch not in charset_set:
                        extra[ch] = extra.get(ch, 0) + 1
    return extra

def main():
    chars = charset()
    cs = set(chars)
    extra = scan_coverage(cs)
    missing = sorted(extra.items(), key=lambda kv: -kv[1])
    print("missing chars (top20):", missing[:20])
    # keep only reasonably frequent extras (skip control oddities)
    add = [c for c, n in missing if n >= 50 and c.isprintable()][:12]
    for c in add:
        chars.append(c)
        print(f"  + added U+{ord(c):04X} ({c!r}) x{extra[c]}")

    font = ImageFont.truetype(TTF, FONT_SIZE)
    asce, desc = font.getmetrics()
    print(f"metrics size={FONT_SIZE}: ascent={asce} descent={desc}")

    # widest glyphs sanity
    widest = ""
    wmax = 0
    for c in chars:
        bb = font.getbbox(c)
        w = bb[2] - bb[0]
        if w > wmax:
            wmax, widest = w, c
    print(f"widest glyph: {widest!r} = {wmax}px")
    if wmax > CELL_W - 1:
        raise SystemExit(f"glyph too wide ({wmax}px), adjust FONT_SIZE/cell")

    rows_out = []
    glyph_index = []
    for c in chars:
        img = Image.new("1", (CELL_W, CELL_H), 0)
        dr = ImageDraw.Draw(img)
        # anchor "ls": left, baseline
        bb = dr.textbbox((0, 0), c, font=font)
        x = -bb[0] if bb[0] < 0 else 0
        try:
            dr.text((x, BASELINE), c, font=font, fill=1, anchor="ls")
        except TypeError:
            dr.text((x, BASELINE - asce), c, font=font, fill=1)
        pix = img.load()
        gr = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if pix[x, y]:
                    bits |= 0x8000 >> x
            gr.append(bits)
        rows_out.append(gr)
        glyph_index.append(ord(c))

    with open(OUT, "w", encoding="ascii") as f:
        f.write("/* font_tr.h -- generated by tools/make_font.py\n"
                f" * DejaVuSansMono.ttf {FONT_SIZE}px, cell {CELL_W}x{CELL_H}, "
                f"{len(chars)} glyphs, baseline {BASELINE} */\n")
        f.write("#ifndef FONT_TR_H\n#define FONT_TR_H\n\n")
        f.write(f"#define TR_FONT_W {CELL_W}\n#define TR_FONT_H {CELL_H}\n")
        f.write(f"#define TR_GLYPH_N {len(chars)}\n\n")
        f.write("static const unsigned short tr_glyphs[TR_GLYPH_N][TR_FONT_H] = {\n")
        for gr in rows_out:
            f.write("    { " + ", ".join(f"0x{b:04X}" for b in gr) + " },\n")
        f.write("};\n\n")
        f.write("static const unsigned short tr_codes[TR_GLYPH_N] = {\n    ")
        line = []
        for code in glyph_index:
            line.append(f"0x{code:04X}")
        for i in range(0, len(line), 12):
            f.write(", ".join(line[i:i + 12]) + ",\n    " if i + 12 < len(line)
                    else ", ".join(line[i:i + 12]) + "\n")
        f.write("};\n\n#endif\n")
    print("wrote", OUT, f"({os.path.getsize(OUT)} bytes, {len(chars)} glyphs)")

if __name__ == "__main__":
    main()
